function makeGuests(tableIndex: number): WeddingTable["guests"] {
  return Array.from({ length: 8 }, (_, seatIndex) => {
    const number = tableIndex * 8 + seatIndex + 1;
    return {
      id: `guest-${number}`,
      name: `Гість ${number}`,
      social: socialPlaceholder,
    };
  });
}

